// UI localisation.
//
// The Settings "Default language" picker (`settings.defaultTargetLanguage`,
// which already steers every AI action's output language) also drives the
// app's own chrome: choosing 日本語 renders the whole interface in Japanese.
//
// Keys ARE the English copy, so an untranslated string degrades to readable
// English instead of a missing-key placeholder, and adding English UI never
// requires touching this file first.

import { useCallback } from "react";
import { useStore } from "./store";

export type UiLang = "en" | "ja";

/** Map the configured default output language to a UI language. */
export function uiLangFor(defaultTargetLanguage: string | undefined | null): UiLang {
  return defaultTargetLanguage === "日本語" ? "ja" : "en";
}

