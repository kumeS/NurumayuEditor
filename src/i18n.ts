/** Translate one English UI string. Unknown keys fall back to the key itself. */
export function translate(key: string, lang: UiLang): string {
  if (lang === "en") return key;
  return JA[key] ?? key;
}

/**
 * Translate outside React (toasts raised from `fileActions`/`aiActions`,
 * where there is no component to hold a hook).
 */
export function tNow(key: string): string {
  return translate(key, uiLangFor(useStore.getState().settings?.defaultTargetLanguage));
}

/** The active UI language — for the few strings that interpolate values and
 *  therefore can't be a single dictionary key (counts, relative times). */
export function useLang(): UiLang {
  return useStore((s) => uiLangFor(s.settings?.defaultTargetLanguage));
}

/** The component-side translator; re-renders when the language setting changes. */
export function useT(): (key: string) => string {
  const lang = useStore((s) => uiLangFor(s.settings?.defaultTargetLanguage));
  return useCallback((key: string) => translate(key, lang), [lang]);
}
